import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const pkg = JSON.parse(await readFile(new URL("package.json", root), "utf8"));

const content = `// Generated by scripts/sync-version.mjs. Do not edit manually.
export const REPORTER_NAME = ${JSON.stringify(pkg.name)};
export const REPORTER_VERSION = ${JSON.stringify(pkg.version)};
`;

await writeFile(new URL("src/version.ts", root), content);
